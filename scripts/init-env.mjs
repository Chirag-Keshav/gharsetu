#!/usr/bin/env node
// Creates a local development .env with random secrets. Refuses to overwrite an existing file.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, '.env');
if (existsSync(target) && !process.argv.includes('--force')) {
  console.log('.env already exists; leaving it unchanged (use --force to regenerate).');
  process.exit(0);
}
const secret = () => randomBytes(32).toString('base64url');
const port = process.env.LOCAL_PG_PORT ?? '54329';

const content = `# Local development settings generated by scripts/init-env.mjs. Never commit this file.
PRODUCT_NAME=
LEGAL_ENTITY_NAME=
SUPPORT_EMAIL=
SUPPORT_PHONE=
NEXT_PUBLIC_PRODUCT_NAME=
NEXT_PUBLIC_LEGAL_ENTITY_NAME=
NEXT_PUBLIC_SUPPORT_EMAIL=
NEXT_PUBLIC_SUPPORT_PHONE=

NODE_ENV=development
API_PORT=4000
WEB_ORIGIN=http://localhost:3000
API_INTERNAL_URL=http://localhost:4000
LOG_LEVEL=info

DATABASE_URL=postgresql://postgres:postgres@localhost:${port}/propcare
TEST_DATABASE_URL=postgresql://postgres:postgres@localhost:${port}/propcare_test

OTP_HMAC_SECRET=${secret()}
# Development only: accepts the fixed code 123456. The API refuses to start in production with this on.
OTP_TEST_MODE=true
COOKIE_SECURE=false
ACCESS_NOTES_KEY=${randomBytes(32).toString('base64')}
STORAGE_SIGNING_SECRET=${secret()}
IP_HASH_SALT=${secret()}

SMS_PROVIDER=console
PAYMENT_PROVIDER=mock
PAYMENT_WEBHOOK_SECRET=${secret()}
STORAGE_DRIVER=local
STORAGE_LOCAL_DIR=.data/storage
MALWARE_SCANNER=none
QUEUE_DRIVER=inprocess
REDIS_URL=
JOBS_ENABLED=true

# AI: "mock" works offline. Set AI_PROVIDER=anthropic and ANTHROPIC_API_KEY to use Claude.
AI_ENABLED=true
AI_PROVIDER=mock
ANTHROPIC_API_KEY=
AI_MODEL_FAST=claude-haiku-5-5
AI_MODEL_SMART=claude-opus-5-5
# Server-side refusal fallback for these tiers (smart|all|none). Haiku has no server-side fallback.
AI_REFUSAL_FALLBACK=smart
`;
writeFileSync(target, content);
console.log(`Wrote ${target}`);
